#include <iostream>

using namespace std;

//Week#3-5

int main()
{
	char a = '~';
	char b = '&';
	char c = '%';
	char d = 'A';

	cout << "ASCII Value Of " << a  << " Is " << (int)a << endl;
	cout << "ASCII Value Of " << b << " Is " << (int)b  << endl;
	cout << "ASCII Value Of " << c << " Is " << (int)c  << endl;
	cout << "ASCII Value Of " << d << " Is " << (int)d  << endl;
	
	return 0;
}

