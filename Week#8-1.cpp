#include <array>
#include <iostream>
#include <string.h>
using namespace std;
//Week#8-1
int main()
{
	// For Output
	
	for (int j = 0; j <=10; j++)
	{
		cout << j << endl;
	}
	cout << "=======================================" << endl;
	// While Output
	short i = 0;
	while (i<=10)
	{
		
		cout << i << endl;
		i++;
	}
	cout << "=======================================" << endl;
	// Do While Output
	int index = 0;
	do
	{	
		cout << index << endl;
		index++;

	} while (index <=10);
	return 0;
}
